// Part-level Bill of Materials — the 5th hierarchy level beneath Component.
// Locomotive → System → Assembly → Component → PART.
//
// Grounded in rail-industry research (DOE/Argonne H2@Rail TCO anchors, Ephraim/TRB
// maintenance-cost allocation, IAS 16 component depreciation, AAR interchange practice).
// Per-unit prices are industry-calibrated ESTIMATES — locomotive parts are quote-only.
// GE-format part numbers marked `pnVerified` follow real catalog schemes (e.g. 142X1050);
// others are plausible-format placeholders.

export type ProcurementType = "new" | "reman" | "unit-exchange" | "consumable";
export type DepreciationMethod = "straight-line" | "units-of-production";
export type Criticality = "Vital" | "Essential" | "Desirable";
export type VedClass = "V" | "E" | "D";
export type AbcClass = "A" | "B" | "C";
export type MaintIntervalUnit = "hrs" | "km" | "months";

export interface Part {
  id: string;
  componentId: string;
  name: string;
  partNumber: string;
  pnVerified: boolean; // true = real OEM catalog number format
  vendor: string;
  partClass: string; // e.g. "Power Assembly", "Consumable", "Electronics"
  procurementType: ProcurementType;
  repairable: boolean;

  // Quantity
  qtyPerComponent: number;
  uom: string;

  // Cost
  unitPriceNew: number;
  unitPriceReman: number; // 0 if not remanufactured
  coreCredit: number; // unit-exchange core return credit
  scrapValue: number; // per-unit end-of-life scrap

  // Life
  lifeYears: number;
  lifeHours: number | null;
  lifeKm: number | null;
  leadTimeWeeks: number;

  // Maintenance
  replacementIntervalYears: number;
  laborHoursPerReplacement: number;
  criticality: Criticality;
  failureImpact: string;
  vedClass: VedClass;

  // Maintenance library — the fields the maintenance schedule and TCO split run on.
  // Interval is expressed in the unit that actually governs the part (hours for
  // engine internals, km for running gear, months for calendar-driven service).
  maintIntervalValue: number;
  maintIntervalUnit: MaintIntervalUnit;
  maintQty: number; // qty consumed per maintenance event
  warrantyYears: number;
  warrantyKm: number;
  failureProbabilityPct: number; // expected chance of failure within the warranty window

  // Depreciation / accounting
  usefulLifeYears: number;
  depreciationMethod: DepreciationMethod;
  capitalized: boolean; // false = expensed consumable

  // Inventory
  onHandQty: number;
  minStock: number;
  maxStock: number;
  reorderPoint: number;
  safetyStock: number;
  annualUsageQty: number;
}

type DerivedField =
  | "id"
  | "onHandQty"
  | "minStock"
  | "maxStock"
  | "reorderPoint"
  | "safetyStock"
  | "annualUsageQty"
  | "maintIntervalValue"
  | "maintIntervalUnit"
  | "maintQty"
  | "warrantyYears"
  | "warrantyKm"
  | "failureProbabilityPct";

type PartSpec = Omit<Part, DerivedField> & Partial<Pick<Part, Exclude<DerivedField, "id">>>;

const ANNUAL_KM_REF = 240000; // ES44AC heavy-freight duty cycle — converts warranty years ↔ km

/**
 * Maintenance interval in the unit that actually governs the part: running hours
 * for engine internals, km for running gear, calendar months for everything else.
 */
function deriveInterval(spec: PartSpec): { value: number; unit: MaintIntervalUnit } {
  if (spec.maintIntervalValue && spec.maintIntervalUnit) {
    return { value: spec.maintIntervalValue, unit: spec.maintIntervalUnit };
  }
  if (spec.lifeHours) return { value: spec.lifeHours, unit: "hrs" };
  if (spec.lifeKm) return { value: spec.lifeKm, unit: "km" };
  return { value: Math.round(spec.replacementIntervalYears * 12), unit: "months" };
}

/**
 * Warranty scales with how critical the part is, capped at its useful life —
 * a 6-month filter never carries a 3-year warranty.
 */
function deriveWarranty(spec: PartSpec): { years: number; km: number } {
  const byCriticality = spec.criticality === "Vital" ? 3 : spec.criticality === "Essential" ? 2 : 1;
  const years = spec.warrantyYears ?? Math.min(byCriticality, Math.max(0.5, spec.usefulLifeYears));
  const km = spec.warrantyKm ?? Math.round((years * ANNUAL_KM_REF) / 10000) * 10000;
  return { years, km };
}

/**
 * Expected failure probability inside the warranty window. Short-interval,
 * high-criticality parts fail more often; clamped to a plausible 2–45% band.
 */
function deriveFailureProbability(spec: PartSpec): number {
  if (spec.failureProbabilityPct != null) return spec.failureProbabilityPct;
  const base = spec.vedClass === "V" ? 18 : spec.vedClass === "E" ? 11 : 6;
  const wearFactor = 8 / Math.max(0.5, spec.replacementIntervalYears);
  return Math.round(Math.min(45, Math.max(2, base * Math.sqrt(wearFactor))));
}

// Derive sensible inventory defaults from criticality + replacement cadence so the
// dataset stays consistent (reorder point = lead-time demand + safety stock).
function withInventory(spec: PartSpec, index: number): Part {
  const fleet = 12; // ES44AC fleet count
  const annualUsage =
    spec.annualUsageQty ??
    Math.max(
      1,
      Math.round((spec.qtyPerComponent * fleet) / Math.max(0.25, spec.replacementIntervalYears)),
    );
  const leadYears = spec.leadTimeWeeks / 52;
  const serviceZ = spec.vedClass === "V" ? 2.33 : spec.vedClass === "E" ? 1.65 : 1.28;
  const safety =
    spec.safetyStock ?? Math.max(1, Math.round(annualUsage * leadYears * serviceZ * 0.4));
  const reorder = spec.reorderPoint ?? Math.round(annualUsage * leadYears + safety);
  const min = spec.minStock ?? safety;
  const max = spec.maxStock ?? Math.max(reorder + 1, Math.round(annualUsage * 0.6) + safety);
  // On-hand: mostly healthy, a few deliberately low to drive the replenishment UI.
  const lowStock = [3, 7, 11, 18, 24].includes(index);
  const onHand =
    spec.onHandQty ?? (lowStock ? Math.max(0, min - 1) : Math.round((reorder + max) / 2));

  const interval = deriveInterval(spec);
  const warranty = deriveWarranty(spec);

  return {
    ...spec,
    id: `prt-${String(index + 1).padStart(3, "0")}`,
    maintIntervalValue: interval.value,
    maintIntervalUnit: interval.unit,
    maintQty: spec.maintQty ?? spec.qtyPerComponent,
    warrantyYears: warranty.years,
    warrantyKm: warranty.km,
    failureProbabilityPct: deriveFailureProbability(spec),
    annualUsageQty: annualUsage,
    safetyStock: safety,
    reorderPoint: reorder,
    minStock: min,
    maxStock: max,
    onHandQty: onHand,
  };
}

